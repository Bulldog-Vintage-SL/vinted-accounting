export function vintedToOplaCategory(catalogId: unknown): string | null {
  let id: number | null = Number(catalogId)
  while (id !== null && Number.isFinite(id)) {
    const code = VINTED_TO_OPLA[id]
    if (code) return code
    id = parentById.get(id) ?? null
  }
  return null
}